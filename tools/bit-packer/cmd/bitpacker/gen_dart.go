package main

// Dart target: `--lang dart`. Writes <schema>.dart: one immutable class
// (final fields, const constructor with named, defaulted parameters, value
// ==/hashCode) per schema class, with encode(): Uint8List and static
// decode(Uint8List) that throws BitPackerException. dart:core,
// dart:convert and dart:typed_data only. `long` is a Dart int, which is
// 64-bit on the Dart VM and AOT but a double under dart2js/JS: the
// generated code is for the VM/AOT/Flutter native only. See docs/dart.md.

import (
	"fmt"
	"strings"
)

func init() { registerGenerator(genDart, "dart") }

